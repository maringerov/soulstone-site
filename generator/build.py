def check_dashes(text: str, where: str) -> None:
    for n, line in enumerate(text.splitlines(), 1):
        for ch, name in DASHES.items():
            if ch in line:
                col = line.index(ch) + 1
                raise BuildError(f"{where}:{n}:{col}: {name} found, use a comma, colon or full stop instead")


