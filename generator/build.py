            f'<p class="mt-3 font-heading text-2xl text-ploy-text-primary">{esc(a["name"])}</p>'
            f'<p class="mt-2 max-w-xl leading-relaxed text-ploy-text-secondary">{esc(a["bio"])}</p>'
