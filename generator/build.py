#!/usr/bin/env python3
"""Soulstone blog generator.

Sources
  posts/*.md            Markdown posts with front matter (title, description,
                        date, tags, optional slug, updated, draft, faq_schema).
  pages/*.md            Markdown static pages (title, description, path,
                        lastmod, optional eyebrow), e.g. /privacy.
  blog/<slug>/index.html  Legacy posts that have no Markdown source. They are
                        parsed for metadata and kept as they are, apart from
                        the author box and the shared head block.
  generator/site.json   Site, author, profile and business configuration.
  generator/templates/  HTML templates cut from the Ploy export.

Outputs (generator-owned, never hand edit)
  blog/<slug>/index.html for every Markdown post, each with one in-article
    Win Chat promo card at the section break nearest the middle of the body
    and one teardown card (a button to /teardown/ plus a line on what the 30
    minutes cover and who they are for) between the body and the author box
    (legacy posts get both cards in place)
  <path>/index.html for every Markdown page
  blog/index.html, tag/<tag>/index.html
  the teardown request form (TEARDOWN_FORM) between the teardown-form markers
    on any page that carries them: the homepage contact section and /teardown/
  the homepage Latest writing list (three newest posts) between the
    latest-writing markers, and the matching const W in the HomePage bundle
  sitemap-0.xml, sitemap-index.xml, rss.xml, site.webmanifest, llms.txt
  the shared head block (og:image, twitter card, RSS link, favicon and app
  icon links, web app manifest, theme-color, mobile navigation styles and
  script, the Win Chat promo banner styles and script, the teardown card and
  mobile hero styles, ProfessionalService and Person JSON-LD) on every HTML
  page, plus the teardown form styles and script on pages that carry the form
  the analytics block (GA4 with Consent Mode defaults and the cookie consent
  bar) right after the viewport meta on every HTML page

The icon files themselves (favicon.svg, favicon.ico, apple-touch-icon.png,
icon-192.png, icon-512.png and the maskable variants) are committed assets at
the repository root, generated by generator/icons.py; the build only links them.

Rules enforced
  * Em dashes and en dashes fail the build. Checked in every Markdown source,
    every template, site.json, every page rendered from Markdown and every
    legacy HTML post. generator/lint.py extends the check to all shipped HTML
    and JS.
  * Banned words fail the build (BANNED_WORDS, case-insensitive): the site
    describes Marin as an independent developer and never uses the usual
    label for a self-employed contractor. Checked in every Markdown source,
    every template, site.json and every finished HTML page after the head
    pass; generator/lint.py extends it to every shipped text file.
  * /blog appears once in the sitemap, every URL carries lastmod, and tag
    pages with fewer than min_tag_posts_in_sitemap posts are left out (and
    marked noindex).
  * No date in the output is later than the build date (today in
    Europe/Amsterdam). A post dated after the build date is skipped with a
    warning: no page, and nothing in the blog index, tag pages, sitemap, RSS
    or llms.txt. Every sitemap lastmod and the RSS lastBuildDate are capped at
    the build date. generator/lint.py fails on any built page whose
    datePublished, or any sitemap lastmod, is later than the lint date.
  * Every post needs its own title and its own meta description. A duplicate
    of either fails the build.
  * Page URLs end in a slash. GitHub Pages serves <dir>/index.html at <dir>/
    and 301-redirects the slashless form, so every page's canonical and og:url
    are set to its own trailing-slash URL, and internal hrefs, astro-island
    header links and JSON-LD url/@id/item fields get the slash too (see
    page_path). Files keep their extension, / stays /.

Usage
  python3 generator/build.py              build in place
  python3 generator/build.py --check      build into a scratch copy and fail
                                          if the committed output differs
  python3 generator/build.py --include-drafts
"""
