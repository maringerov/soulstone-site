    for n, line in enumerate(text.splitlines(), 1):
        for pat, hint in BANNED_WORDS.items():
            m = pat.search(line)
            if m:
                raise BuildError(f"{where}:{n}:{m.start() + 1}: banned word {m.group(0)!r}, {hint}")


